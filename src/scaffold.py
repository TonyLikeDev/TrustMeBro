#!/usr/bin/env python3
"""
scaffold.py - Project Scaffolder and Standard Layout Auditor for RoadmapFlow.
Generates and audits standard 3-tier folder structures for any project using RoadmapFlow.

# ponytail: Zero-dependency stdlib script; generates full standard tree or audits compliance in one file.
"""

import argparse
import sys
from datetime import date
from pathlib import Path
from typing import Dict, List, Tuple

from roadmap import estimate_tokens, render_ascii_bar


# --- Templates conforming to RoadmapFlow standards ---

def get_plan_template(name: str, stack: str, phases: int) -> str:
    today = date.today().isoformat()
    lines = [
        f"# Project Plan: {name}",
        "",
        "> Static master plan. Edit to refine the plan; never edit to record progress — use ROADMAP.md.",
        "",
        "## Overview",
        f"- Goal: Build and ship {name}",
        f"- Stack: {stack}",
        "- Deliverables: Production-ready codebase, tests, and documentation",
        f"- Timeline: {phases} phases",
        "- Team: Core Engineering",
        "",
        "## Decisions Log",
        "| Topic | Option A | Option B | Decision | Reason |",
        "| :--- | :--- | :--- | :--- | :--- |",
        f"| Architecture | Monolith | Microservices | Modular monolith | Minimal operational overhead |",
        "",
    ]

    for p in range(1, phases + 1):
        lines.extend([
            f"## Phase {p}: {'Foundation & Infrastructure' if p == 1 else f'Feature Module {p}'}",
            "### Build",
            f"- [ ] Core skeleton for Phase {p} in `src/`",
            f"- [ ] Module implementation and interfaces",
            "### Measure",
            f"- [ ] Automated unit tests in `tests/test_phase_{p}.py`",
            "### Write",
            f"- [ ] Architecture notes in `docs/phase_{p}.md`",
            "### Exit criteria",
            "- [ ] All phase unit tests pass with zero regressions",
            "",
        ])

    lines.extend([
        "## Risks and Fallbacks",
        "| Risk | Signal | Fallback |",
        "| :--- | :--- | :--- |",
        "| Scope creep | Phase has > 8 tasks | Split phase into sub-phases |",
        "",
    ])
    return "\n".join(lines)


def get_roadmap_template(name: str, phases: int) -> str:
    today = date.today().isoformat()
    bar_empty = render_ascii_bar(0.0)
    lines = [
        f"# Roadmap and Status — {name}",
        "",
        "Master plan: `PLAN.md`. This file is the live status board.",
        "**Rule: tick items here in the same commit as the work. Never edit PLAN.md to record progress.**",
        "",
        "Legend: `[x]` done · `[~]` written but not verified · `[ ]` open",
        "",
        f"Last updated: {today}",
        "",
        "## Progress",
        "",
        "<!-- progress:start -->",
        f"**Progress: 0% of the project plan** `{bar_empty}` · Active scope: 0% `{bar_empty}`",
        "",
        "| Phase / Week | Items | Done | Progress | |",
        "| :--- | ---: | ---: | :--- | ---: |",
    ]

    for p in range(1, phases + 1):
        lines.append(f"| Phase {p} | 4 | 0 | `{bar_empty}` | not started |")

    lines.extend([
        "",
        "_Generated by `scripts/roadmap_progress.py` from the checkboxes below; rerun it after ticking items._",
        "<!-- progress:end -->",
        "",
        "---",
        "",
    ])

    for p in range(1, phases + 1):
        lines.extend([
            f"## Phase {p}: {'Foundation & Infrastructure' if p == 1 else f'Feature Module {p}'}",
            "",
            "### Build",
            f"- [ ] Core skeleton for Phase {p} in `src/`",
            f"- [ ] Module implementation and interfaces",
            "",
            "### Measure",
            f"- [ ] Automated unit tests in `tests/test_phase_{p}.py`",
            "",
            "### Write",
            f"- [ ] Architecture notes in `docs/phase_{p}.md`",
            "",
            "### Exit criteria",
            "- [ ] All phase unit tests pass with zero regressions",
            "",
            "---",
            "",
        ])

    lines.extend([
        "## Immediate next actions (in order)",
        f"1. Setup repository structure and execute Phase 1 Build tasks.",
        "2. Implement tests and verify exit criteria.",
        "",
        "## Change log",
        f"- {today}: Initial plan and roadmap generated by RoadmapFlow.",
        "",
    ])
    return "\n".join(lines)


def get_architecture_template(name: str, stack: str) -> str:
    today = date.today().isoformat()
    return f"""# Architecture Snapshot — {name}

> Tier 1 context: always load this file at session start. Target size: ≤ 500 tokens.
> Last updated: {today}

## What this project is
High-performance system for {name}. Produces deterministic execution, verifiable milestones, and clean code.

## Stack
- Language/runtime: {stack}
- Architecture: Modular, test-driven, 3-tier context management

## Key Decisions
- Strict 3-Tier Context: Tier 1 (always in context) + Tier 2 (session snapshot) to avoid LLM context bloat.
- Binary Exit Criteria: Every phase must pass objective exit verification before moving to next phase.

## Source Layout
- `src/`: Core implementation modules
- `tests/`: Automated unit & integration tests
- `docs/`: Technical specifications and reports
- `scripts/`: Operational tools and progress hooks
- `.bob/context/`: Tier 1 (`architecture.md`) and Tier 2 (`current-phase.md`)

## What NOT to re-read every session
- `PLAN.md`: Full multi-phase plan (static archive — query via subagent)
- `ROADMAP.md`: Completed phases history (use `.bob/context/current-phase.md` instead)
"""


